import { contextBridge, ipcRenderer, webUtils } from "electron";
import type { ControlEvent, Frame, MediaEvent, NetConfig, VjBridge } from "../core/frame";

const bridge: VjBridge = {
  onControl: cb => { ipcRenderer.on("control", (_e, ev: ControlEvent) => cb(ev)); },
  publishFrame: f => { ipcRenderer.send("frame", f); },
  gpuLost: () => { ipcRenderer.send("gpu:lost"); },
  onFrame: cb => { ipcRenderer.on("frame", (_e, f: Frame) => cb(f)); },
  listDisplays: () => ipcRenderer.invoke("displays:list"),
  toggleOutput: id => ipcRenderer.invoke("displays:toggle", id),
  windowOutputSize: (w, h) => ipcRenderer.invoke("displays:windowSize", w, h),
  configure: (c: NetConfig) => { ipcRenderer.send("configure", c); },
  addMedia: p => { ipcRenderer.send("media:add", p); },
  removeMedia: id => { ipcRenderer.send("media:remove", id); },
  onMedia: cb => { ipcRenderer.on("media", (_e, ev: MediaEvent) => cb(ev)); },
  saveProject: json => { ipcRenderer.send("project:save", json); },
  onDisplays: cb => { ipcRenderer.on("displays", (_e, d) => cb(d)); },
  setUiScale: v => { ipcRenderer.send("ui:scale", v); },
  askMicrophone: () => ipcRenderer.invoke("audio:ask"),
  askCamera: () => ipcRenderer.invoke("camera:ask"),
  openPrivacy: kind => { ipcRenderer.send("privacy:open", kind); },
  pathForFile: f => webUtils.getPathForFile(f),
  addVideo: (p, n) => ipcRenderer.invoke("video:add", p, n),
  removeVideo: id => { ipcRenderer.send("video:remove", id); },
  sendArtTimecode: (b, host) => { ipcRenderer.send("tc:artnet", b, host); },
  loadProject: () => ipcRenderer.invoke("project:load"),
  projectFile: (cmd, json, filePath) => ipcRenderer.invoke("project:file", cmd, json, filePath),
  projectDirty: dirty => { ipcRenderer.send("project:dirty", dirty); },
  projectBaseline: hash => { ipcRenderer.send("project:baseline", hash); },
  projectRecent: () => ipcRenderer.invoke("project:recent"),
  clearRecent: () => ipcRenderer.invoke("project:clearRecent"),
  onMenu: cb => { ipcRenderer.on("menu", (_e, cmd: string, arg?: string) => cb(cmd, arg)); },
  platform: process.platform,
  liveMedia: e => { ipcRenderer.send("media:live", e); },
  ljFetch: path => ipcRenderer.invoke("lj:fetch", path),
  ljStatus: s => { ipcRenderer.send("lj:status", s); },
  openLj: () => { ipcRenderer.send("lj:open"); },
  updateCheck: force => ipcRenderer.invoke("update:check", force),
  updateInstall: () => ipcRenderer.invoke("update:install"),
  onUpdate: cb => { ipcRenderer.on("update", (_e, st) => cb(st)); },
  openWeb: url => { ipcRenderer.send("web:open", url); },
  setLang: (lang, reload) => { ipcRenderer.send("ui:lang", lang, reload === true); },
};
contextBridge.exposeInMainWorld("vj", bridge);
